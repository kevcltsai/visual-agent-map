// Generates i18n/han-variants.ts: Traditional -> Simplified single-character pairs.
// Source: macOS built-in ICU transform "Hant-Hans" via CFStringTransform (no download; decision D-2026-10-87).
// Run from the repo root:  swift scripts/gen-han-variants.swift
// Header records the macOS version and Swift toolchain used; the output is sorted by code point (deterministic).
// Unicode data is licensed under the Unicode License v3; see NOTICE.
import Foundation

func transform(_ s: String) -> String? {
  let m = NSMutableString(string: s)
  return CFStringTransform(m as CFMutableString, nil, "Hant-Hans" as CFString, false) ? (m as String) : nil
}

let ranges: [ClosedRange<UInt32>] = [0x3400...0x4DBF, 0x4E00...0x9FFF]
var traditional = ""
var simplified = ""
var count = 0
for range in ranges {
  for code in range {
    guard let scalar = Unicode.Scalar(code) else { continue }
    let source = String(Character(scalar))
    guard let out = transform(source), out.unicodeScalars.count == 1, out != source else { continue }
    traditional.unicodeScalars.append(scalar)
    simplified += out
    count += 1
  }
}

let os = ProcessInfo.processInfo.operatingSystemVersionString
let output = """
// GENERATED by scripts/gen-han-variants.swift - do not edit by hand.
// Source: macOS ICU transform "Hant-Hans" (CFStringTransform), \(os).
// Pairs: \(count) single Traditional characters whose Simplified form is a different single character,
// from CJK Unified Ideographs U+4E00-U+9FFF and Extension A U+3400-U+4DBF, sorted by code point.
// Unicode data copyright (c) Unicode, Inc.; licensed under the Unicode License v3 (see NOTICE).
export const HAN_TRADITIONAL =
  "\(traditional)";
export const HAN_SIMPLIFIED =
  "\(simplified)";

"""
try output.write(toFile: "i18n/han-variants.ts", atomically: true, encoding: .utf8)
print("pairs: \(count)")
